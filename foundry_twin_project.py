def _crop_box(annotation, image_size, padding=24):
    x0, y0, x1, y1 = annotation["bbox_xyxy"]
    return (max(0, x0 - padding), max(0, y0 - padding),
            min(image_size[0], x1 + padding), min(image_size[1], y1 + padding))

def export_defect_closeups(metadata, out_dir, padding=24, enlargement=4):
    if not isinstance(padding, int) or isinstance(padding, bool) or padding < 0:
        raise ValueError("padding must be a nonnegative integer.")
    if not isinstance(enlargement, int) or isinstance(enlargement, bool) or not 1 <= enlargement <= 16:
        raise ValueError("enlargement must be an integer from 1 to 16.")
    out = Path(out_dir)
    folder = out / "closeups"
    folder.mkdir(parents=True, exist_ok=True)
    with Image.open(out / "clean_reference.png") as im:
        clean = im.convert("RGB")
    index = []
    for record in metadata["chips"]:
        if not record["annotations"]:
            continue
        with Image.open(out / record["image_path"]) as im:
            raw = im.convert("RGB")
        with Image.open(out / "instance_masks" / f"{record['chip_id']}.png") as im:
            instances = im.copy()
        for annotation in record["annotations"]:
            crop = _crop_box(annotation, raw.size, padding)
            detail = raw.crop(crop)
            reference = clean.crop(crop)
            mask = np.asarray(instances.crop(crop)) == annotation["instance_id"]
            spec = DEFECT_CLASSES[annotation["class_id"]]
            rgb = np.zeros((*mask.shape, 3), dtype=np.uint8)
            rgb[mask] = [255, 255, 255]
            stem = f"{record['chip_id']}_defect_{annotation['instance_id']:02d}"
            paths = {key: f"closeups/{stem}_{suffix}.png" for key, suffix in [
                ("raw_path", "raw"), ("clean_path", "clean"), ("mask_path", "mask"),
                ("mask_color_path", "mask_color"), ("enlarged_path", "enlarged")
            ]}
            detail.save(out / paths["raw_path"])
            reference.save(out / paths["clean_path"])
            Image.fromarray(mask.astype(np.uint8) * 255).save(out / paths["mask_path"])
            Image.fromarray(rgb).save(out / paths["mask_color_path"])
            detail.resize((detail.width * enlargement, detail.height * enlargement),
                          Image.Resampling.NEAREST).save(out / paths["enlarged_path"])
            item_data = {"chip_id": record["chip_id"], **annotation,
                         "crop_xyxy": list(crop), "native_size_px": list(detail.size),
                         "pixel_enlargement": enlargement, "physical_magnification": None}
            item_data.update(paths)
            index.append(item_data)
    (out / "closeups.json").write_text(json.dumps(index, indent=2), encoding="utf-8")
    return index

def plot_chip_gallery(metadata, out_dir, show=True):
    out = Path(out_dir)
    spec = _profile_from_metadata(metadata)
    records = metadata["chips"]
    selected = [("No visible defect", next((r for r in records if r["defect_count"] == 0), None), "#A7C6CC")]
    used = set()
    for kind, defect in DEFECT_CLASSES.items():
        row = next((r for r in records if any(a["class_id"] == kind for a in r["annotations"])), None)
        if row is not None:
            used.add(row["chip_id"])
        selected.append((defect["label"], row, defect["color"]))
    fig, axes = plt.subplots(2, 3, figsize=(14, 11), facecolor="#0C1520")
    for ax, (title, row, color) in zip(axes.flat, selected):
        if row:
            with Image.open(out / row["annotated_path"]) as im:
                ax.imshow(im)
            detail = f"{row['chip_id']} / {row['defect_count']} inserted defect(s)"
        else:
            ax.text(.5, .5, "No example in this sample", ha="center", color="#A8BBC9", transform=ax.transAxes)
            detail = "No synthetic example forced"
        ax.set_title(title, loc="left", color=color, fontsize=12, fontweight="bold", pad=10)
        ax.set_axis_off()
    fig.suptitle(spec["label"] + " / synthetic compute-tile inspection", x=.055, y=.98,
                ha="left", color="white", fontsize=18, weight="bold")
    fig.text(.055, .935, f"{spec['status']}\n{metadata['n_chips']} sampled chips / {metadata['total_defects']} defects / seed {metadata['seed']}",
             color="#A8BBC9", fontsize=11, linespacing=1.6)
    fig.text(.055, .025, "Known insertions, not detector predictions. A clean-looking tile can still fail parameterically. No physical scale.",
             color="#A8BBC9", fontsize=10)
    fig.subplots_adjust(left=.055, right=.96, top=.87, bottom=.08, wspace=.12, hspace=.24)
    _finish_inspection_figure(fig, out / "chip_defect_gallery.pdf", show)
    return selected

