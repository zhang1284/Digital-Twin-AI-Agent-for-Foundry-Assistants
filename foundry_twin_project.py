def run_panther_inspections(source_scenario, output_dir="outputs/panther_inspection",
                            n_chips=32, seed=42, class_weights=None, variant_scenarios=None,
                            show=True, include_teaching_examples=True):
    scenarios = variant_scenarios if variant_scenarios is not None else {
        key: source_scenario for key in INSPECTION_PROFILES
    }
    if set(scenarios) != set(INSPECTION_PROFILES):
        raise ValueError("variant_scenarios must contain intel_18a and intel_18a_p.")
    config = {"render_version": 2, "scenarios": {k: asdict(s) for k, s in scenarios.items()},
              "n_chips": n_chips, "seed": seed, "class_weights": list(class_weights) if class_weights is not None else None,
              "include_teaching_examples": bool(include_teaching_examples)}
    run_key = hashlib.sha256(json.dumps(config, sort_keys=True, allow_nan=False).encode()).hexdigest()[:12]
    root = Path(output_dir) / f"run_{run_key}"
    datasets, directories = {}, {}
    for key, current in scenarios.items():
        out = root / key
        data = generate_chip_dataset(current, out, n_chips=n_chips, seed=seed,
                                     class_weights=class_weights, profile=key)
        datasets[key], directories[key] = data, out
        plot_chip_gallery(data, out, show=False)
        if include_teaching_examples:
            export_teaching_examples(out, key, seed, show=False)
    comparison_path = root / "panther_inspection_comparison.png"
    plot_panther_comparison(datasets, directories, comparison_path, show=show)
    for key in INSPECTION_PROFILES:
        plot_defect_closeup(datasets[key], directories[key], show=show)
    manifest = {"config": config, "profiles": INSPECTION_PROFILES, "context_sources": INTEL_CONTEXT_SOURCES,
                "datasets": {key: str(path.relative_to(root)) for key, path in directories.items()}}
    (root / "run_manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    (root / "README.txt").write_text(
        "FOUNDRY TWIN / PANTHER LAKE SYNTHETIC INSPECTION\n\n"
        "Intel 18A is the Panther lake compute-tile process context. The 18A-P\n"
        "Panther Lake pairing is a hypothetical comparison. Layouts are invented.\n"
        "Only the single-die model's compute-tile proxy is inspected; other package\n"
        "tiles are decorative. No Intel PDK, wafer images, or real defect/yield data.\n\n"
        "Default: unchanged scenario and same seed for both labels. Therefore the\n"
        "two samples have equal counts by design, not as a real process comparison.\n"
        "Pass/fail still includes independent parametric failures without visible defects.\n\n"
        "Per profile: annotations.json, chip_summary.csv, images/, annotated/,\n"
        "class_masks/, instance_masks/, processor_package_view.png,\n"
        "closeups/ includes every sampled defect at native resolution and 4x pixel\n"
        "enlargement. Boxes and masks are insertion ground truth, not predictions.\n"
        "Coordinates are xyxy pixels, right/bottom exclusive. No physical scale.\n"
        "teaching_examples/ contains forced examples, excluded from ALL statistics.\n\n"
        "Naming context only (not simulation calibration):\n" + "\n".join(INTEL_CONTEXT_SOURCES) + "\n",
        encoding="utf-8"
    )
    zip_path = Path(shutil.make_archive(str(root), "zip", root))
    for key, data in datasets.items():
        print(f"{INSPECTION_PROFILES[key]['label']}: {data['n_chips']} chips, "
              f"{data['total_defects']} defects; sampled model yield {data['sampled_yield']:.1%}")
    print("18A-P Panther Lake is hypothetical. All images use synthetic, uncalibrated model data.")
    print(f"Saved images, all defect crops, masks and metadata: {root}")
    print(f"ZIP: {zip_path}")
    return {"datasets": datasets, "output_dirs": directories, "output_dir": root,
            "comparison_path": comparison_path, "zip_path": zip_path}

