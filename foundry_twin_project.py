def _read_inspection_rows(scenario, path):
  """Validate CSV fields, counts, areas, sources and unique lot IDs."""
  required = {"process", "lot_id", "defects", "inspected_area_cm2", "source_kind"}
  with Path(path).open(newline="", encoding="utf-8-sig") as f:
      reader = csv.DictReader(f)
      if not required <= set(reader.fieldnames or []):
          raise ValueError(f"Telemetry requires columns: {', '.join(sorted(required))}")
      if len(set(reader.fieldnames)) != len(reader.fieldnames):
           raise ValueError("Telemetry column headers must be unique.")
      rows = list(reader)
  selected, ignored, seen = [], 0, set()
  for row in rows:
      if None in row or any(row.get(key) is None for key in required):
          raise ValueError("A telemetry row does not match its header.")
      if row["process"] != scenario.process.key:
          ignored += 1
          continue
      lot = row["lot_id"].strip()
      if not lot or lot in seen:
          raise ValueError("Matching telemetry needs nonempty, unique lot_id values.")
      seen.add(lot)
      try:
         defects = int(row["defects"])
         area = float(row["inspected_area_cm2"])
      except (TypeError, ValueError) as exc:
          raise ValueError(f"Invalid telemetry values in lot {lot}.") from exc
      integer("defects", defects, 0, 10**9)
      number("inspected_area_cm2", area, 0.000001, 1e12)
      if row["source_kind"] not in {"synthetic", "measured"}:
          raise ValueError("source_kind must be synthetic or measured.")
      selected.append((defects, area, row["source_kind"]))
  if not selected:
      raise ValueError(f"No telemetry matches process {scenario.process.key}.")
  return selected, ignored

