def _simulation_report(scenario, area, tops, power, temperature,
                       allowed_frequency, gross, yield_fraction, good, cost):
    """Add production estimates, goal checks and the fields used by later cells."""
    d, p, g = scenario.design, scenario.process, scenario.goals

    capacities = {s.name: s.parallel_tools * 24 * s.availability
                / (s.hours_per_visit * s.visits_per_wafer) for s in scenario.stages}
    bottleneck = min(capacities, key=capacities.get)
    wafers_per_day = capacities[bottleneck]
    first_wafer_days = sum(s.hours_per_visit * s.visits_per_wafer / s.availability
                             for s in scenario.stages) /24

    # Fluid pipeline approximation, with zero initial qeue and continuous tools
    lot_days = first_wafer_days + (scenario.wafers - 1) / wafers_per_day
    checks: list[dict[str, Any]] = []

    def check(name: str, observed: Any, relation: str, limit: Any, passed: bool) -> None:
        checks.append(dict(
            name=name, observed=observed, relation=relation,
            limit=limit, passed=bool(passed)
        ))

    check ("Voltage floor", d.voltage_v, ">=", p.min_voltage_v, d.voltage_v >= p.min_voltage_v)
    check ("Voltage ceiling", d.voltage_v, "<=", p.max_voltage_v, d.voltage_v <= p.max_voltage_v)
    check("Frequency at voltage (surrogate)", d.frequency_ghz, "<=", allowed_frequency,
          d.frequency_ghz <= allowed_frequency + 1e-9)
    check("Die area mm2", area, "<=", p.max_die_area_mm2, area <= p.max_die_area_mm2)
    check("Gross die per wafer", gross, ">=", 1, gross >= 1)
    check("Performance TOPS", tops, ">=", g.min_tops, tops >= g.min_tops)
    check("Power W", power, "<=", g.max_power_w, power <= g.max_power_w)
    check("Junction temperature °C", temperature, "<=", g.max_junction_c, temperature <= g.max_junction_c)
    check("Yield fraction", yield_fraction, ">=", g.min_yield, yield_fraction >= g.min_yield)
    check("Cost per good die USD", cost, "<=", g.max_cost_per_good_die_usd,
          cost is not None and cost <= g.max_cost_per_good_die_usd)
    check("Lot duration days", lot_days, "<=", g.max_lot_days, lot_days <= g.max_lot_days)

    return {
          "model_version": VERSION, "notice": NOTICE, "scenario": asdict(scenario),
          "process": p.key, "provenance": p.provenance,
          "metrics": {"area_mm2": area, "performance_tops": tops, "power_w": power,
          "junction_c": temperature, "allowed_frequency_ghz": allowed_frequency,
          "gross_dies_per_wafer": gross, "yield_fraction": yield_fraction,
          "expected_good_dies_per_wafer": good, "expected_good_dies_in_lot": good *
  scenario.wafers,
          "cost_per_good_die_usd": cost, "wafer_capacity_per_day": wafers_per_day,
          "good_die_capacity_per_day": wafers_per_day * good, "lot_days": lot_days,
        },
          "stage_capacity_wafers_per_day": capacities, "bottleneck": bottleneck,
          "checks": checks, "feasible": all(c["passed"] for c in checks),
          "violations": [c["name"] for c in checks if not c["passed"]],

}

def _candidate_grid(scenario, processes=None):
    """Build the original bound grid, including the baseline settings."""
    processes = [scenario.process] if processes is None else processes
    if not processes or len(processes) > 10:
        raise ValueError("Choose between 1 and 10 processes.")
    base = scenario.design
    units = sorted({max(1, min(4096, round(base.compute_units * x))) for x in [0.75, 1, 1.25, 1.5]})
    frequencies = sorted({round(max(0.1, min(10, base.frequency_ghz * x)), 4)
                          for x in (0.75, 0.9, 1, 1.1, 1.25)})
    voltages = sorted({round(max(0.3, min(2, base.voltage_v + x)), 4) for x in (-0.15, -0.05,
  0, 0.05, 0.15)})
    return itertools.product(processes, units, frequencies, voltages)

