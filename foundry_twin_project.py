def _load_documents(notes_dir):
    documents = [dict(d) for d in KNOWLEDGE]

    if notes_dir is None:
        return documents
    directory = Path(notes_dir)
    if not directory.is_dir():
        raise ValueError(f"Notes directory does not exist: {directory}")
    for path in sorted(directory.iterdir()):
        if not path.is_file() or path.suffix.lower() not in ({".md", ".txt"}):
            continue
        words = path.read_text(encoding="utf-8")

        for start in range(0, len(words), 140):
            documents.append({"id": f"{path.name}:{start // 140 + 1}",
                            "source": path.name,
                            "text": " ".join(words[start:start + 180]),
            })
    return documents

