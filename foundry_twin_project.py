STOPWARDS = set("a an the is are to of in and for with what how does can my our me it this that do".split())

def tokens(text: str) -> list[str]:
    return [t for t in re.findall("r[a-z0-9]+", text.lower()) if t not in STOPWARDS]
def catalog_search(path: str | Path, query: str = "", limit: int = 10) -> dict[str, Any]:
  """Read arbitrary processor CSV columns without inventing a vendor schema."""
  integer("limit", limit, 1, 100)
  with Path(path).open(encoding="utf-8-sig", newLine="") as f:
              reader = csv.DictReader(f)
              fields = reader.fieldnames
              if not fields or any(not x.strip() for x in fields) or len(set(fields) != len(fields)):
                  raise ValueError("Processor CSV needs nonempty, unique colummn headers.")
              matches, rows = [], 0
              for row in reader:
                  rows += 1
                  if None in row or any(v is None for v in row.values()):
                      raise ValueError("Processor CSV needs nonempty, unique column headers.")
                  if query.lower() in " ".join(row.values()).lower() and len(matches) < limit:
                      matches.append(row)
  return {"file": Path(path).name, "columns": fields, "rows_scanned": rows,
          "matches": matches, "note": "User-supplied catalog records; not fab telemetry or process rules."}

class RunStore:
    """SQLite experiment log. Inputs and outputs travel together for reproducability."""
    def __init__(self, path: str | Path):
        self.path = Path(path)
        self.path.parent.mkdir(parents=True, exist_ok=True)
        with sqlite3.connect(self.path) as db:
            db.execute("""
                CREATE TABLE IF NOT EXISTS runs (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                created_utc TEXT NOT NULL,
                kind TEXT NOT NULL,
                payload_json TEXT NOT NULL) """
                )
    def save(self, kind: str, payload: Any) -> int:
        with sqlite3.connect(self.path) as db:
          cursor = db.execute(
              "INSERT INTO runs (created_utc, kind, payload_json) VALUES (?, ?, ?)",
              (datetime.now(timezone.utc).isoformat(), kind, json_text(payload)),

          )
          return int(cursor.lastrowid)

    def recent(self, limit: int = 10) -> list[dict[str, Any]]:
        integer("limit", limit, 1, 100)
        with sqlite3.connect(self.path) as db:
            rows = db.execute("SELECT id, created_utc, kind FROM runs ORDER BY id DESC LIMIT ?" , (limit,)).fetchall()
        return [dict(zip(("id", "created_utc", "kind"), row)) for row in rows]

