def simulate(scenario: Scenario) -> dict[str, Any]:
    """Evaluate one design with deterministic, explicitly simplified equations."""
    d, p = scenario.design, scenario.process
    area = (d.fixed_area_mm2 + d.compute_units * d.area_per_unit_mm2) * p.area_scale
    tops = d.compute_units * d.ops_per_cycle_per_unit * d.frequency_ghz
    power = (p.dynamic_power_coefficient * d.compute_units * d.frequency_ghz
             * d.voltage_v**2 + p.leakage_w_per_mm2 * area)
    temperature = d.ambient_c + power * d.thermal_resistance_c_per_w
    voltage_fraction = (d.voltage_v - p.min_voltage_v) / (p.max_voltage_v - p.min_voltage_v)
    allowed_frequency = p.max_frequency_ghz * (0.40 + 0.60 * max(0, min(1, voltage_fraction)))
    pitch_area = (math.sqrt(area) + p.scribe_lane_mm)**2
    effective_diameter = p.wafer_diameter_mm - 2 * p.edge_exclusion_mm
    gross = max(0, math.floor(math.pi * (effective_diameter / 2)**2 / pitch_area
                            -math.pi * effective_diameter / math.sqrt(2 * pitch_area)))
    yield_fraction = math.exp(-area / 100 * p.defect_density_per_cm2) * p.parametric_yield
    good = gross * yield_fraction
    cost = ((p.wafer_cost_usd + gross * p.test_cost_per_gross_die_usd) / good
            + p.packaging_per_good_die_usd) if good > 0 else None
    return _simulation_report(scenario, area, tops, power, temperature,
                              allowed_frequency, gross, yield_fraction, good, cost)

def sample_lot(scenario: Scenario) -> dict[str, Any]:
  """Sample independent die pass/fail events for a reproducaible synthetic lot.

  This is a binomial teaching model, not calibrated prcoess uncertainty.
  A work limit prevents accidentally doing billions of Python terations.
  """

  r = simulate(scenario)
  if r is None:
      return {
          "notice": NOTICE,
          "seed": scenario.seed,
          "wafers": [],
          "sampled_good_dies": 0,
          "expected_good_dies": 0.0,
          "binomial_standard_deviation": 0.0
      }
  gross, y = r["metrics"]["gross_dies_per_wafer"], r["metrics"]["yield_fraction"]
  n = gross * scenario.wafers
  if n > 2_000_000:
      raise ValueError("Sample lot exceeds 2 million dies; reduce wafers or use analytical simulation.")
  rng = random.Random(scenario.seed)
  rows = [{"wafer": i + 1, "gross_dies": gross,
          "good_dies": sum(rng.random() < y for _ in range(gross))}
          for i in range(scenario.wafers)]
  return {"notice": NOTICE, "seed": scenario.seed, "wafers": rows,
          "sampled_good_dies": sum(row["good_dies"] for row in rows),
          "expected_good_dies": n * y, "binomial_standard_deviation": math.sqrt(n * y * (1 - y))}

def optimize(scenario, processes=None):
    """Find the cheapest feasible design on the supplied search grid."""
    base = scenario.design
    feasible, rejected = [], Counter()
    count = 0
    for p, u, f, v in _candidate_grid(scenario, processes):
        candidate = replace(scenario, process=p, design=replace(base, compute_units=u,
                            frequency_ghz=f, voltage_v=v))
        result = simulate(candidate)
        count += 1
        if result is None:
            continue
        if result.get("feasible", False):
            feasible.append(result)
        else:
            rejected.update(result["violations"])
    return _optimization_report(scenario, feasible, rejected, count)

def calibrate_from_csv(scenario, path):
  """Estimate defects per cm^2 from non-overlapping inspected areas."""
  selected, ignored = _read_inspection_rows(scenario, path)
  defects = sum(r[0] for r in selected)
  area = sum(r[1] for r in selected)
  density = defects / area
  kind = ", ".join(sorted({r[2] for r in selected}))
  sha = hashlib.sha256(Path(path).read_bytes()).hexdigest()
  updated = replace(scenario, process=replace(scenario.process, defect_density_per_cm2=density,
        provenance=f"Detect estimate from {kind} telemetry; other parameters remain assumed."))
  return updated, {"process": scenario.process.key, "lots_used": len(selected),
                   "rows_ignored_other_processes": ignored, "defects": defects, "inspected_area_cm2": area,
                   "old_defect_density_per_cm2": scenario.process.defect_density_per_cm2,
                   "new_defect_density_per_cm2": density, "source_kind": kind, "source_sha256": sha,
                   "note": "Point estimate only. Inspection coverage and defect detection efficicency are not modeled."}

class KnowledgeBase:
    """Search project notes using offline TF-IDF scores."""
    def __init__(self, notes_dir=None):
        self.documents = _load_documents(notes_dir)
        self.counts = [Counter(tokens(d["text"])) for d in self.documents]
        df = Counter(t for counts in self.counts for t in counts)
        self.idf = {t: math.log((1 + len(self.counts)) / (1 + n)) + 1 for t, n in df.items()}

    def search(self, query: str, k: int = 3) -> list[dict[str, Any]]:
        if not isinstance(query, str) or not query.strip() or len(query) > 10000:
            raise ValueError("Question must contain 1-10000 characters.")
        integer("k", k, 1, 20)
        q = {t: n * self.idf[t] for t, n in Counter(tokens(query)).items() if t in self.idf}
        qnorm = math.sqrt(sum(x*x for x in q.values()))
        if not qnorm:
            return []
        hits = []
        for document, counts in zip(self.documents, self.counts):
            vector = {t: n * self.idf[t] for t, n in counts.items()}
            norm = math.sqrt(sum(x*x for x in vector.values()))
            score = sum(v * vector.get(t, 0) for t, v in q.items()) / (qnorm * norm) if norm else 0
            if score > 0:
                hits.append({**document, "score": round(score, 5)})
        return sorted(hits, key=lambda d: d["score"], reverse=True)[:k]

def post_openai(payload: dict[str, Any], api_key: str) -> dict[str, Any]:
    """Send a JSON payload to the OpenAI Responses API using python's built-in HTTPS client."""
    req = urllib.request.Request(
        "https://api.openai.com/v1/responses",
        data=json.dumps(payload).encode("utf-8"),
        headers={
            "Content-Type": "application/json",
            "Authorization": f"Bearer {api_key}",
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=60) as resp:
            return json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
       body = exc.read().decode("utf-8", errors="replace")
       raise RuntimeError(f"OpenAI API HTTP {exc.code}: {body}") from exc
    except urllib.error.URLError as exc:
        raise RuntimeError(f"OpenAI API connection failed: {exc.reason}") from exc

def _validate_tool_arguments(name: str, arguments: Any) -> None:
    """Validate tool names and strict JSON schema arguments before execution."""
    allowed_tools = {
        "simulate_design",
        "optimize_design",
        "get_inspection_summary",
        "retrieve_notes",
    }
    if name not in allowed_tools:
        raise KeyError(r"Unknown or disallowed tool: {name}")
    if not isinstance(arguments, dict):
        raise TypeError("Tool arguments must be a JSON object.")
    if name == "retrieve_notes":
        if set(arguments.keys()) != {"query"}:
            raise ValueError("retrieve_notes 'query' must be a non-empty string.")
    elif arguments:
        raise ValueError(f"Tool '{name}' takes no arguments.")

class FoundryAssistant:
    """Connect questions to the current scenario, notes and inspection sample."""
    def __init__(self, scenario=None, knowledge=None, inspection_data=None, wafer_data=None):
        self.scenario = scenario or Scenario()
        self.knowledge = knowledge or KnowledgeBase()
        self.inspection_data = inspection_data
        self.wafer_data = wafer_data

    def execute_tool(self, name, arguments):
        _validate_tool_arguments(name, arguments)
        actions = {
            "simulate_design": lambda: simulate(self.scenario),
            "optimize_design": lambda: optimize(self.scenario),
            "get_inspection_summary": self.inspection_summary,
            "retrieve_notes": lambda: {"sources": self.knowledge.search(arguments["query"])},


        }
        return actions[name]()

    def inspection_summary(self):
        return _inspection_summary(self)

    def offline(self, question):
        return _offline_answer(self, question)

    def llm(self, question, model=None, api_key=None, transport=None, max_rounds=6):
        return _openai_answer(self, question, model, api_key, transport, max_rounds)

